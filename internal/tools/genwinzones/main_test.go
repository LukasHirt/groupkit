func doc(zones string) string {
	return `<?xml version="1.0"?><supplementalData><windowsZones><mapTimezones otherVersion="x" typeVersion="y">` +
		zones + `</mapTimezones></windowsZones></supplementalData>`
}

func TestParseKeepsTerritory001AndSorts(t *testing.T) {
	in := doc(`
<mapZone other="W. Europe Standard Time" territory="DE" type="Europe/Berlin"/>
<mapZone other="W. Europe Standard Time" territory="001" type="Europe/Berlin"/>
<mapZone other="Eastern Standard Time" territory="001" type="America/New_York"/>
<mapZone other="Eastern Standard Time" territory="CA" type="America/Toronto America/Montreal"/>
<mapZone other="UTC" territory="001" type="Etc/UTC"/>`)
	got, err := parse(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	want := []entry{
		{"Eastern Standard Time", "America/New_York"},
		{"UTC", "Etc/UTC"},
		{"W. Europe Standard Time", "Europe/Berlin"},
	}
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("entry %d = %v, want %v", i, got[i], want[i])
		}
	}
}

func TestParseRejectsBadInput(t *testing.T) {
	cases := map[string]string{
		"non-ascii":     `<mapZone other="Zürich Time" territory="001" type="Europe/Zurich"/>`,
		"overlong":      `<mapZone other="` + strings.Repeat("A", 101) + `" territory="001" type="Europe/Zurich"/>`,
		"quote":         `<mapZone other="A&quot;B" territory="001" type="Europe/Zurich"/>`,
		"newline":       `<mapZone other="A&#10;B" territory="001" type="Europe/Zurich"/>`,
		"empty":         `<mapZone other="" territory="001" type="Europe/Zurich"/>`,
		"empty iana":    `<mapZone other="A" territory="001" type=""/>`,
		"bad iana":      `<mapZone other="A" territory="001" type="Europe/Zu rich"/>`,
		"iana quote":    `<mapZone other="A" territory="001" type="Europe/&quot;x"/>`,
		"multi iana":    `<mapZone other="A" territory="001" type="Europe/Zurich Europe/Berlin"/>`,
		"overlong iana": `<mapZone other="A" territory="001" type="` + strings.Repeat("a", 101) + `"/>`,
	}
	for name, zone := range cases {
		if _, err := parse(strings.NewReader(doc(zone))); err == nil {
			t.Errorf("%s: expected an error", name)
		}
	}
}

func TestParseIgnoresInvalidOutsideTerritory001(t *testing.T) {
	in := doc(`<mapZone other="A" territory="001" type="Etc/UTC"/>
<mapZone other="Zürich" territory="CH" type="Europe/Zurich Europe/Berlin"/>`)
	if _, err := parse(strings.NewReader(in)); err != nil {
		t.Fatal(err)
	}
}

func TestParseRejectsEmptyResult(t *testing.T) {
	if _, err := parse(strings.NewReader(doc(""))); err == nil {
		t.Fatal("expected an error for no territory 001 entries")
	}
}

func TestRenderIsValidGo(t *testing.T) {
	src, err := render("release-x", []entry{{"A Time", "Etc/A"}, {"B Time", "Etc/B"}})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "x.go", src, parser.AllErrors); err != nil {
		t.Fatalf("generated code does not parse: %v\n%s", err, src)
	}
	formatted, err := format.Source(src)
	if err != nil {
		t.Fatal(err)
	}
	if string(formatted) != string(src) {
		t.Errorf("output is not gofmt-clean:\n%s", src)
	}
	s := string(src)
	for _, want := range []string{
		"// Code generated by internal/tools/genwinzones; DO NOT EDIT.",
		"// SPDX-FileCopyrightText: Unicode, Inc.",
		"// SPDX-License-" + "Identifier: Unicode-3.0",
		"release-x",
		"package ical",
		`"A Time": "Etc/A",`,
		"func lookupWindowsZone(name string) (string, bool)",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("output lacks %q", want)
		}
	}
}
