// Command genwinzones generates ical/winzones_gen.go from the Unicode CLDR
// windowsZones.xml file. The input is treated as untrusted: every value is
// validated and emitted only through %q-quoted string literals.
package main

import (
	"bytes"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"sort"
	"time"
)

// cldrTag is the CLDR release the table is generated from.
const cldrTag = "release-46-1"

const (
	maxInput   = 4 << 20
	maxNameLen = 100
)

var ianaPattern = regexp.MustCompile(`^[A-Za-z0-9_+\-/]+$`)

type entry struct {
	Windows string
	IANA    string
}

type mapZone struct {
	Other     string `xml:"other,attr"`
	Territory string `xml:"territory,attr"`
	Type      string `xml:"type,attr"`
}

type document struct {
	Zones []mapZone `xml:"windowsZones>mapTimezones>mapZone"`
}

func main() {
	url := flag.String("url", "https://raw.githubusercontent.com/unicode-org/cldr/"+cldrTag+"/common/supplemental/windowsZones.xml", "URL of windowsZones.xml")
	file := flag.String("file", "", "read windowsZones.xml from this local file instead of downloading")
	out := flag.String("out", "winzones_gen.go", "output file")
	flag.Parse()

	if err := run(*url, *file, *out); err != nil {
		fmt.Fprintln(os.Stderr, "genwinzones:", err)
		os.Exit(1)
	}
}

func run(url, file, out string) error {
	var r io.ReadCloser
	if file != "" {
		f, err := os.Open(file)
		if err != nil {
			return err
		}
		r = f
	} else {
		client := &http.Client{Timeout: 30 * time.Second}
		resp, err := client.Get(url)
		if err != nil {
			return err
		}
		if resp.StatusCode != http.StatusOK {
			_ = resp.Body.Close()
			return fmt.Errorf("fetching %s: %s", url, resp.Status)
		}
		r = resp.Body
	}
	defer func() { _ = r.Close() }()

	entries, err := parse(io.LimitReader(r, maxInput+1))
	if err != nil {
		return err
	}
	src, err := render(cldrTag, entries)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

// parse reads the CLDR document, keeps the territory 001 entries, validates
// them and returns them sorted by Windows name.
func parse(r io.Reader) ([]entry, error) {
	data, err := io.ReadAll(io.LimitReader(r, maxInput+1))
	if err != nil {
		return nil, err
	}
	if len(data) > maxInput {
		return nil, fmt.Errorf("input exceeds %d bytes", maxInput)
	}
	var doc document
	if err := xml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("parsing XML: %w", err)
	}
	seen := map[string]bool{}
	var entries []entry
	for _, z := range doc.Zones {
		if z.Territory != "001" {
			continue
		}
		if err := validateName("Windows name", z.Other); err != nil {
			return nil, err
		}
		if err := validateName("IANA name", z.Type); err != nil {
			return nil, err
		}
		if !ianaPattern.MatchString(z.Type) {
			return nil, fmt.Errorf("IANA name %q has unexpected characters", z.Type)
		}
		if seen[z.Other] {
			return nil, fmt.Errorf("duplicate Windows name %q", z.Other)
		}
		seen[z.Other] = true
		entries = append(entries, entry{Windows: z.Other, IANA: z.Type})
	}
	if len(entries) == 0 {
		return nil, fmt.Errorf("no territory 001 entries found")
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Windows < entries[j].Windows })
	return entries, nil
}

func validateName(what, s string) error {
	if s == "" {
		return fmt.Errorf("%s is empty", what)
	}
	if len(s) > maxNameLen {
		return fmt.Errorf("%s %q is longer than %d bytes", what, s[:20], maxNameLen)
	}
	for i := 0; i < len(s); i++ {
		if s[i] < 0x20 || s[i] > 0x7e {
			return fmt.Errorf("%s %q contains a non-printable or non-ASCII byte", what, s)
		}
	}
	if bytes.ContainsAny([]byte(s), "\"`\\") {
		return fmt.Errorf("%s %q contains a quote or backslash", what, s)
	}
	return nil
}

func render(tag string, entries []entry) ([]byte, error) {
	if err := validateName("release tag", tag); err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tools/genwinzones; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// " + "SPDX-FileCopyrightText: Unicode, Inc.\n")
	b.WriteString("//\n")
	b.WriteString("// SPDX-License-" + "Identifier: Unicode-3.0\n\n")
	fmt.Fprintf(&b, "// Generated from the Unicode CLDR release %s (windowsZones.xml, territory 001).\n\n", tag)
	b.WriteString("package ical\n\n")
	b.WriteString("// windowsZones maps Windows time zone names to IANA time zone names.\n")
	b.WriteString("var windowsZones = map[string]string{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%q: %q,\n", e.Windows, e.IANA)
	}
	b.WriteString("}\n\n")
	b.WriteString("// lookupWindowsZone returns the IANA name for a Windows time zone name.\n")
	b.WriteString("// The match is exact and case-sensitive.\n")
	b.WriteString("func lookupWindowsZone(name string) (string, bool) {\n")
	b.WriteString("\tiana, ok := windowsZones[name]\n")
	b.WriteString("\treturn iana, ok\n")
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
